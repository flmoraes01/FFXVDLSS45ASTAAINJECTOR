# Generates src/proxy_exports.h: forwards every export of System32\winmm.dll to the real system copy.
import os
import pefile

BS = '\\'
# Linker sees:  \\.\GLOBALROOT\SystemRoot\System32\winmm   -> in a C literal every backslash is doubled.
target = BS * 2 + '.' + BS + 'GLOBALROOT' + BS + 'SystemRoot' + BS + 'System32' + BS + 'winmm'
c_target = target.replace(BS, BS * 2)

pe = pefile.PE(os.path.expandvars(r'%SystemRoot%\System32\winmm.dll'), fast_load=True)
pe.parse_data_directories(directories=[0])
lines = ['// Generated by tools/gen_proxy.py - forwards all winmm.dll exports to the system copy', '#pragma once']
for e in pe.DIRECTORY_ENTRY_EXPORT.symbols:
    if e.name:
        n = e.name.decode()
        lines.append(f'#pragma comment(linker, "/export:{n}={c_target}.{n},@{e.ordinal}")')
    else:
        lines.append(f'#pragma comment(linker, "/export:__ord{e.ordinal}={c_target}.#{e.ordinal},@{e.ordinal},NONAME")')
with open(os.path.join(os.path.dirname(__file__), '..', 'src', 'proxy_exports.h'), 'w') as f:
    f.write('\n'.join(lines) + '\n')
print(len(lines) - 2, 'exports')
